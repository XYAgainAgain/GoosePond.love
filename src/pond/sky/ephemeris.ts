function lunar(jd: number): Vec3 {
  const t = (jd - J2000) / 36525;
  const lp =
    (218.3164477 + 481267.88123421 * t - .0015786 * t * t + t ** 3 / 538841 - t ** 4 / 65194000) *
    DEG;
  const d =
    (297.8501921 + 445267.1114034 * t - .0018819 * t * t + t ** 3 / 545868 - t ** 4 / 113065000) *
    DEG;
  const m = (357.5291092 + 35999.0502909 * t - .0001536 * t * t + t ** 3 / 24490000) * DEG;
  const mp =
    (134.9633964 + 477198.8675055 * t + .0087414 * t * t + t ** 3 / 69699 - t ** 4 / 14712000) *
    DEG;
  const f =
    (93.2720950 + 483202.0175233 * t - .0036539 * t * t - t ** 3 / 3526000 + t ** 4 / 863310000) *
    DEG;
  const e = 1 - .002516 * t - .0000074 * t * t;
  let lon = 0, radius = 0, lat = 0;
  for (const [a, b, c, h, l, r] of LR) {
    const arg = a * d + b * m + c * mp + h * f, factor = e ** Math.abs(b);
    lon += l * factor * Math.sin(arg);
    radius += r * factor * Math.cos(arg);
  }
  for (const [a, b, c, h, v] of B) {
    lat += v * e ** Math.abs(b) * Math.sin(a * d + b * m + c * mp + h * f);
  }
  const a1 = (119.75 + 131.849 * t) * DEG,
    a2 = (53.09 + 479264.290 * t) * DEG,
    a3 = (313.45 + 481266.484 * t) * DEG;
  lon += 3958 * Math.sin(a1) + 1962 * Math.sin(lp - f) + 318 * Math.sin(a2);
  lat += -2235 * Math.sin(lp) + 382 * Math.sin(a3) + 175 * Math.sin(a1 - f) +
    175 * Math.sin(a1 + f) +
    127 * Math.sin(lp - mp) - 115 * Math.sin(lp + mp);
  const lambda = lp + lon * DEG / 1e6, beta = lat * DEG / 1e6, r = (385000.56 + radius / 1000) / AU;
  const eps = (23 + 26 / 60 + (21.448 - 46.815 * t - .00059 * t * t + .001813 * t ** 3) / 3600) *
    DEG;
  return eclipticToEqu([
    r * Math.cos(beta) * Math.cos(lambda),
    r * Math.cos(beta) * Math.sin(lambda),
    r * Math.sin(beta),
  ], eps);
}

// Astronomical Almanac phase laws; Saturn includes ring opening and the difference in ring longitudes.
function magnitude(
  index: number,
  phase: number,
  r: number,
  delta: number,
  geo: Vec3,
  helio: Vec3,
  jd: number,
): number {
  const a = phase / DEG;
  const distance = 5 * Math.log10(r * delta);
  switch (index) {
    case 0:
      return distance - .42 + .0380 * a - .000273 * a * a + .000002 * a ** 3;
    case 1:
      return distance - 4.40 + .0009 * a + .000239 * a * a - .00000065 * a ** 3;
    case 3:
      return distance - 1.52 + .016 * a;
    case 4:
      return distance - 9.40 + .005 * a;
    default: {
      const t = (jd - J2000) / 36525;
      const eps =
        (23 + 26 / 60 + (21.448 - 46.815 * t - .00059 * t * t + .001813 * t ** 3) / 3600) * DEG;
      const p = precession(jd);
      geo = eclipticToEqu(transform(p, eclipticToEqu(geo, 23.439291111 * DEG)), -eps);
      helio = eclipticToEqu(transform(p, eclipticToEqu(helio, 23.439291111 * DEG)), -eps);
      const inc = (28.075216 - .012998 * t + .000004 * t * t) * DEG;
      const node = (169.508470 + 1.394681 * t + .000412 * t * t) * DEG;
      const normal: Vec3 = [
        Math.sin(inc) * Math.sin(node),
        -Math.sin(inc) * Math.cos(node),
        Math.cos(inc),
      ];
      const opening = Math.abs(dot(normal, scale(geo, -1 / delta)));
      const axis: Vec3 = [Math.cos(node), Math.sin(node), 0];
      const other: Vec3 = [
        -Math.sin(node) * Math.cos(inc),
        Math.cos(node) * Math.cos(inc),
        Math.sin(inc),
      ];
      const longitude = (v: Vec3) => Math.atan2(dot(v, other), dot(v, axis));
      const du = Math.abs(
        Math.atan2(
          Math.sin(longitude(geo) - longitude(helio)),
          Math.cos(longitude(geo) - longitude(helio)),
        ),
      ) / DEG;
      return distance - 8.88 + .044 * du - 2.60 * opening + 1.25 * opening * opening;
    }
  }
}

export function skyAt(ms: number, latDeg: number, lonDeg: number): Ephemeris {
  const jd = jdFromMs(ms), tt = dynamicalJd(jd);
  const lst = sidereal(jd, lonDeg), lat = latDeg * DEG;
  const local = localMatrix(lst, lat), p = precession(tt);
  const moonEqu = lunar(tt);
  const earth = orbit(2, tt);
  const eps0 = 23.439291111 * DEG;
  // The orbital table gives the Earth–Moon barycenter, not Earth's center.
  const moonJ2000: Vec3 = [
    p[0] * moonEqu[0] + p[3] * moonEqu[1] + p[6] * moonEqu[2],
    p[1] * moonEqu[0] + p[4] * moonEqu[1] + p[7] * moonEqu[2],
    p[2] * moonEqu[0] + p[5] * moonEqu[1] + p[8] * moonEqu[2],
  ];
  const moonEcl = eclipticToEqu(moonJ2000, -eps0);
  for (let i = 0; i < 3; i++) earth[i] -= moonEcl[i] / 82.30056;
  const u = Math.atan(.99664719 * Math.tan(lat));
  const observer: Vec3 = [
    6378.137 / AU * Math.cos(u) * Math.cos(lst),
    6378.137 / AU * Math.cos(u) * Math.sin(lst),
    6378.137 / AU * .99664719 * Math.sin(u),
  ];
  const position = (equ: Vec3): BodyPosition => {
    const top = sub(equ, observer), distance = norm(top), unit = scale(top, 1 / distance);
    return {
      direction: transform(local, unit),
      ra: wrap(Math.atan2(top[1], top[0])),
      dec: Math.asin(unit[2]),
      distance,
    };
  };
  const toDate = (ecl: Vec3) => transform(p, eclipticToEqu(ecl, eps0));
  const sunEqu = toDate(scale(earth, -1));
  const sun = position(sunEqu), moonBase = position(moonEqu);
  const sunFromMoon = sub(sunEqu, moonEqu), observerFromMoon = sub(observer, moonEqu);
  const phase = acos(
    dot(sunFromMoon, observerFromMoon) / (norm(sunFromMoon) * norm(observerFromMoon)),
  );
  const dra = sun.ra - moonBase.ra;
  const moon: MoonPosition = {
    ...moonBase,
    illuminatedFraction: (1 + Math.cos(phase)) / 2,
    brightLimbAngle: Math.atan2(
      Math.cos(sun.dec) * Math.sin(dra),
      Math.sin(sun.dec) * Math.cos(moonBase.dec) -
        Math.cos(sun.dec) * Math.sin(moonBase.dec) * Math.cos(dra),
    ),
  };
  const planets = {} as Record<PlanetName, PlanetPosition>;
  const names: PlanetName[] = ["mercury", "venus", "mars", "jupiter", "saturn"];
  for (let n = 0; n < names.length; n++) {
    const index = n < 2 ? n : n + 1;
    let helio = orbit(index, tt), geo = sub(helio, earth);
    for (let i = 0; i < 2; i++) {
      helio = orbit(index, tt - norm(geo) * .0057755183);
      geo = sub(helio, earth);
    }
    const r = norm(helio), delta = norm(geo);
    const phaseAngle = acos(dot(helio, geo) / (r * delta));
    planets[names[n]] = {
      ...position(toDate(geo)),
      phaseAngle,
      magnitude: magnitude(index, phaseAngle, r, delta, geo, helio, tt),
    };
  }
  return { localSiderealTime: lst, sun, moon, planets };
}

