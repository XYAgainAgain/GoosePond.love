function orbit(index: number, jd: number): Vec3 {
  const t = (jd - J2000) / 36525;
  if (index >= 4) {
    // The long-range Kepler fit alone misses the angular budget for these two planets.
    const eps = (23 + 26 / 60 + (21.448 - 46.815 * t - .00059 * t * t + .001813 * t ** 3) / 3600) *
      DEG;
    const equ = eclipticToEqu(outerEcliptic(index, jd), eps), p = precession(jd);
    return eclipticToEqu([
      p[0] * equ[0] + p[3] * equ[1] + p[6] * equ[2],
      p[1] * equ[0] + p[4] * equ[1] + p[7] * equ[2],
      p[2] * equ[0] + p[5] * equ[1] + p[8] * equ[2],
    ], -23.439291111 * DEG);
  }
  const [base, rate] = ELEMENTS[index];
  const [a, e, i, l, peri, node] = base.map((v, n) => v + rate[n] * t);
  const m = wrap((l - peri) * DEG);
  let E = m;
  for (let n = 0; n < 8; n++) E -= (E - e * Math.sin(E) - m) / (1 - e * Math.cos(E));
  const x = a * (Math.cos(E) - e), y = a * Math.sqrt(1 - e * e) * Math.sin(E);
  const w = (peri - node) * DEG, o = node * DEG, inc = i * DEG;
  const cw = Math.cos(w), sw = Math.sin(w), co = Math.cos(o), so = Math.sin(o), ci = Math.cos(inc);
  return [
    (cw * co - sw * so * ci) * x + (-sw * co - cw * so * ci) * y,
    (cw * so + sw * co * ci) * x + (-sw * so + cw * co * ci) * y,
    sw * Math.sin(inc) * x + cw * Math.sin(inc) * y,
  ];
}
function eclipticToEqu(v: Vec3, eps: number): Vec3 {
  return [
    v[0],
    Math.cos(eps) * v[1] - Math.sin(eps) * v[2],
    Math.sin(eps) * v[1] + Math.cos(eps) * v[2],
  ];
}

