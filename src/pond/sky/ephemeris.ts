const DEG = Math.PI / 180;
const AU = 149597870.7;
const J2000 = 2451545;
export type Vec3 = [number, number, number];
export type PlanetName = "mercury" | "venus" | "mars" | "jupiter" | "saturn";

/** Angles are radians, distances are AU, and directions are airless [west, up, south]. */
export interface BodyPosition {
  direction: Vec3;
  ra: number;
  dec: number;
  distance: number;
}
export interface PlanetPosition extends BodyPosition {
  magnitude: number;
  phaseAngle: number;
}
export interface MoonPosition extends BodyPosition {
  illuminatedFraction: number;
  /** Position angle from celestial north toward east, before local sky projection. */
  brightLimbAngle: number;
}
export interface Ephemeris {
  localSiderealTime: number;
  sun: BodyPosition;
  moon: MoonPosition;
  planets: Record<PlanetName, PlanetPosition>;
}

export function jdFromMs(ms: number): number {
  return ms / 86400000 + 2440587.5;
}
const wrap = (x: number) => ((x % (2 * Math.PI)) + 2 * Math.PI) % (2 * Math.PI);
const norm = (v: Vec3) => Math.hypot(...v);
const dot = (a: Vec3, b: Vec3) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
const sub = (a: Vec3, b: Vec3): Vec3 => [a[0] - b[0], a[1] - b[1], a[2] - b[2]];
const scale = (a: Vec3, s: number): Vec3 => [a[0] * s, a[1] * s, a[2] * s];
const acos = (x: number) => Math.acos(Math.max(-1, Math.min(1, x)));

// Historical dynamical time follows the NASA eclipse polynomial; future UTC keeps the last known offset.
function dynamicalJd(jd: number): number {
  const y = 2000 + (jd - J2000) / 365.2425;
  let dt = 69.184;
  if (y < 1600) {
    const u = (y - 1000) / 100;
    dt = 1574.2 - 556.01 * u + 71.23472 * u ** 2 + 0.319781 * u ** 3 - 0.8503463 * u ** 4 -
      0.005050998 * u ** 5 + 0.0083572073 * u ** 6;
  } else if (y < 1700) {
    const t = y - 1600;
    dt = 120 - 0.9808 * t - 0.01532 * t * t + t ** 3 / 7129;
  } else if (y < 1800) {
    const t = y - 1700;
    dt = 8.83 + 0.1603 * t - 0.0059285 * t ** 2 + 0.00013336 * t ** 3 - t ** 4 / 1174000;
  } else if (y < 1860) {
    const t = y - 1800;
    dt = 13.72 - 0.332447 * t + 0.0068612 * t ** 2 + 0.0041116 * t ** 3 - 0.00037436 * t ** 4 +
      0.0000121272 * t ** 5 - 0.0000001699 * t ** 6 + 0.000000000875 * t ** 7;
  } else if (y < 1900) {
    const t = y - 1860;
    dt = 7.62 + 0.5737 * t - 0.251754 * t ** 2 + 0.01680668 * t ** 3 - 0.0004473624 * t ** 4 +
      t ** 5 / 233174;
  } else if (y < 1920) {
    const t = y - 1900;
    dt = -2.79 + 1.494119 * t - 0.0598939 * t ** 2 + 0.0061966 * t ** 3 - 0.000197 * t ** 4;
  } else if (y < 1941) {
    const t = y - 1920;
    dt = 21.20 + 0.84493 * t - 0.0761 * t ** 2 + 0.0020936 * t ** 3;
  } else if (y < 1961) {
    const t = y - 1950;
    dt = 29.07 + 0.407 * t - t ** 2 / 233 + t ** 3 / 2547;
  } else if (y < 1986) {
    const t = y - 1975;
    dt = 45.45 + 1.067 * t - t ** 2 / 260 - t ** 3 / 718;
  } else if (y < 2005) {
    const t = y - 2000;
    dt = 63.86 + 0.3345 * t - 0.060374 * t ** 2 + 0.0017275 * t ** 3 + 0.000651814 * t ** 4 +
      0.00002373599 * t ** 5;
  } else if (y < 2020) {
    const t = y - 2000;
    dt = 62.92 + 0.32217 * t + 0.005589 * t ** 2;
  }
  return jd + dt / 86400;
}

function sidereal(jd: number, lon: number): number {
  const t = (jd - J2000) / 36525;
  return wrap(
    (280.46061837 + 360.98564736629 * (jd - J2000) + 0.000387933 * t * t -
      t ** 3 / 38710000 + lon) * DEG,
  );
}

// IAU 1976 precession as one matrix over catalog vectors, not per star.
function precession(jd: number): Float64Array {
  const t = (jd - J2000) / 36525;
  const zeta = (2306.2181 * t + 0.30188 * t ** 2 + 0.017998 * t ** 3) * DEG / 3600;
  const z = (2306.2181 * t + 1.09468 * t ** 2 + 0.018203 * t ** 3) * DEG / 3600;
  const theta = (2004.3109 * t - 0.42665 * t ** 2 - 0.041833 * t ** 3) * DEG / 3600;
  const a = Math.cos(zeta), b = Math.sin(zeta), c = Math.cos(z), d = Math.sin(z);
  const e = Math.cos(theta), f = Math.sin(theta);
  return new Float64Array([
    c * e * a - d * b,
    -c * e * b - d * a,
    -c * f,
    d * e * a + c * b,
    -d * e * b + c * a,
    -d * f,
    f * a,
    -f * b,
    e,
  ]);
}
function transform(m: Float64Array, v: Vec3): Vec3 {
  return [
    m[0] * v[0] + m[1] * v[1] + m[2] * v[2],
    m[3] * v[0] + m[4] * v[1] + m[5] * v[2],
    m[6] * v[0] + m[7] * v[1] + m[8] * v[2],
  ];
}
function localMatrix(lst: number, lat: number): Float64Array {
  const s = Math.sin(lst), c = Math.cos(lst), p = Math.sin(lat), q = Math.cos(lat);
  return new Float64Array([s, -c, 0, q * c, q * s, p, p * c, p * s, -q]);
}
/** Row-major matrix: local[row] = sum(matrix[row × 3 + column] × J2000[column]). */
export function equToLocal(ms: number, latDeg: number, lonDeg: number): Float64Array {
  const jd = jdFromMs(ms);
  const l = localMatrix(sidereal(jd, lonDeg), latDeg * DEG);
  const p = precession(dynamicalJd(jd));
  const result = new Float64Array(9);
  for (let r = 0; r < 3; r++) {
    for (let c = 0; c < 3; c++) {
      for (let k = 0; k < 3; k++) result[r * 3 + c] += l[r * 3 + k] * p[k * 3 + c];
    }
  }
  return result;
}

